"""Track a recorded path with MPPI: Gazebo + TurtleBot3 + RViz + mppi_tracker.

Usage:
    ros2 launch mppi_nav mppi.launch.py case:=case1        # path + obstacle world of a test case
    ros2 launch mppi_nav mppi.launch.py path:=my_recording.csv            # empty world
    ros2 launch mppi_nav mppi.launch.py path:=case1.csv world:=case2      # mix and match
    ros2 launch mppi_nav mppi.launch.py path:=/abs/path/my.csv x_pose:=0 y_pose:=0 yaw:=0
    ros2 launch mppi_nav mppi.launch.py case:=dynamic                 # boxes dropped while driving
    ros2 launch mppi_nav mppi.launch.py case:=loop                    # smooth self-crossing loop + drops
    ros2 launch mppi_nav mppi.launch.py case:=case1 spawn:=manual     # drop boxes on request:
        ros2 service call /drop_obstacle std_srvs/srv/Trigger

The robot holds still until /odom, /scan and TF are live, then waits `start_delay`
seconds (default 10) so Gazebo and RViz can finish loading, then starts tracking.
Start early with:  ros2 service call /start_tracking std_srvs/srv/Trigger

`path` is an absolute path, or a file name looked up in the package's installed
paths/ folder and then in `paths_dir` (the source paths/ folder, so a fresh
recording works without rebuilding).

By default the robot is spawned on the first path point, facing along the first
path segment, so it starts on the path. The same spawn pose is given to the
tracker, because Gazebo's odometry starts at (0, 0, 0) at the spawn pose.
"""
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import AppendEnvironmentVariable, DeclareLaunchArgument, LogInfo, OpaqueFunction
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node

from mppi_nav.data_dirs import data_dir
from mppi_nav.launch_utils import (pose_topic, resolve_csv, sim_actions, spawn_pose_from_path,
                                   world_file_for)


def launch_setup(context, *args, **kwargs):
    share = get_package_share_directory('mppi_nav')
    arg = lambda n: LaunchConfiguration(n).perform(context)  # noqa: E731

    # ---- case / path / world ----
    case, path_arg, world = arg('case'), arg('path'), arg('world')
    if not path_arg and not case:
        raise ValueError('give case:=<case1|case2|case3|case4|dynamic> or path:=<csv>')
    if not world:                       # default: the case's world, else no obstacles
        world = case if (case and not path_arg) else 'empty'
    csv_file = resolve_csv(path_arg or f'{case}.csv', share, arg('paths_dir'))

    # ---- spawn pose ----
    auto = spawn_pose_from_path(csv_file)
    x = auto[0] if arg('x_pose') == 'auto' else float(arg('x_pose'))
    y = auto[1] if arg('y_pose') == 'auto' else float(arg('y_pose'))
    yaw = auto[2] if arg('yaw') == 'auto' else float(arg('yaw'))

    # ---- world (worlds/<name>.sdf, generated by sim2d/scenarios.py) ----
    world_file = world_file_for(world, share)
    use_ekf = arg('use_ekf').lower() == 'true'

    traversed = arg('traversed_file')
    if traversed == 'auto':
        stem = os.path.splitext(os.path.basename(csv_file))[0]
        traversed = os.path.join(data_dir('results'), f'{stem}_traversed.csv')

    # Gazebo, patched robot, bridges, EKF, RViz: shared with record.launch.py
    sim = sim_actions(world_file, x, y, yaw, use_ekf, arg('gui'), arg('use_rviz'))
    tracker = Node(
        package='mppi_nav', executable='mppi_tracker', name='mppi_tracker', output='screen',
        emulate_tty=True,
        parameters=[arg('params_file'), {
            'use_sim_time': True,
            'path_file': csv_file,
            'start_x': x, 'start_y': y, 'start_yaw': yaw,
            'traversed_file': traversed,
            'start_delay': float(arg('start_delay')),
            'odom_topic': pose_topic(use_ekf),
        }])
    info = LogInfo(msg=f'[mppi.launch] path={csv_file}\n[mppi.launch] world={world_file}\n'
                       f'[mppi.launch] spawn x={x:.3f} y={y:.3f} yaw={yaw:.3f} rad\n'
                       f'[mppi.launch] pose source: '
                       f'{"EKF /odometry/filtered (wheels + IMU gyro)" if use_ekf else "raw wheel /odom"}\n'
                       f'[mppi.launch] robot starts {arg("start_delay")} s after all inputs '
                       'are live (or: ros2 service call /start_tracking std_srvs/srv/Trigger)')
    # ---- dynamic obstacles (obstacle_spawner + Gazebo create/remove services) ----
    spawn_mode = arg('spawn') or ('auto' if case in ('dynamic', 'loop') else 'off')
    spawner_nodes = []
    if spawn_mode != 'off':
        spawner_nodes = [
            Node(package='ros_gz_bridge', executable='parameter_bridge', name='spawn_bridge',
                 output='screen',
                 arguments=['/world/default/create@ros_gz_interfaces/srv/SpawnEntity',
                            '/world/default/remove@ros_gz_interfaces/srv/DeleteEntity']),
            Node(package='mppi_nav', executable='obstacle_spawner', name='obstacle_spawner',
                 output='screen', emulate_tty=True,
                 parameters=[os.path.join(share, 'config', 'obstacle_spawner.yaml'), {
                     'path_file': csv_file, 'start_x': x, 'start_y': y, 'start_yaw': yaw,
                     'odom_topic': pose_topic(use_ekf),
                     'mode': spawn_mode,
                 }]),
        ]

    return [info] + sim + [tracker] + spawner_nodes


def generate_launch_description() -> LaunchDescription:
    share = get_package_share_directory('mppi_nav')
    args = [
        DeclareLaunchArgument('case', default_value='',
                              description='case1|case2|case3|case4|case4b|dynamic|loop: '
                                          'loads paths/<case>.csv and worlds/<case>.sdf'),
        DeclareLaunchArgument('path', default_value='',
                              description='CSV path file (absolute, or a name in paths/)'),
        DeclareLaunchArgument('paths_dir', default_value=data_dir('paths'),
                              description='Extra folder searched for relative CSV names'),
        DeclareLaunchArgument('world', default_value='',
                              description="worlds/<name>.sdf: empty|case1|case2|case3|...; "
                                          "default = the case's world, or empty"),
        DeclareLaunchArgument('spawn', default_value='',
                              description="dynamic boxes: off | auto | manual "
                                          "(default: auto for case:=dynamic and case:=loop, else off)"),
        DeclareLaunchArgument('use_ekf', default_value='true',
                              description='fuse wheel odometry + IMU gyro (robot_localization); '
                                          'false = raw wheel odometry'),
        DeclareLaunchArgument('start_delay', default_value='10.0',
                              description='[s] hold the robot this long after all inputs are live'),
        DeclareLaunchArgument('x_pose', default_value='auto', description="spawn x or 'auto'"),
        DeclareLaunchArgument('y_pose', default_value='auto', description="spawn y or 'auto'"),
        DeclareLaunchArgument('yaw', default_value='auto', description="spawn yaw or 'auto'"),
        DeclareLaunchArgument('params_file',
                              default_value=os.path.join(share, 'config', 'mppi_params.yaml')),
        DeclareLaunchArgument('traversed_file', default_value='auto',
                              description="CSV for the driven path; 'auto' = results/<path>_traversed.csv, '' = off"),
        DeclareLaunchArgument('use_rviz', default_value='true'),
        DeclareLaunchArgument('gui', default_value='true', description='Gazebo GUI'),
    ]
    tb3_models = os.path.join(get_package_share_directory('turtlebot3_gazebo'), 'models')
    return LaunchDescription(args + [
        AppendEnvironmentVariable('GZ_SIM_RESOURCE_PATH', tb3_models),
        OpaqueFunction(function=launch_setup),
    ])
